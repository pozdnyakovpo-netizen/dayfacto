"""Отсев по СТАДИИ события, а не по теме и не по глаголу.

Агентская лента публикует каждый чих на каждой стадии: предложил,
обсудил, пообещал, внёс, рассмотрел, принял. Читателю нужна одна —
та, после которой что-то реально меняется.

    намерение   -> мимо   (пообещал, потребовал, выступил за)
    процедура   -> мимо   (обсудили, встретился, поблагодарил)
    свершилось  -> берём  (подписал закон, вступает в силу, пожар)
    практика    -> берём  (предупредили о мошенниках, о расписании)

Фильтр намеренно грубый и работает только по заголовку: его дело —
снять дешёвый мусор и сэкономить вызовы модели. Тонкий отбор
(«событие случилось, но читателю оно безразлично») — работа
классификатора relevance, а не регулярных выражений.
"""

from __future__ import annotations

import re

# Свершившийся факт перебивает протокольную форму глагола:
# «Путин подписал закон» протокольный по форме, но это решение.
HAPPENED = re.compile(
    r"(подписал (закон|указ|постановлен)|вступ(ает|ил|ит) в силу|"
    r"принят(о|ы)? закон|утвердил(и)? правил|"
    r"подорожа|подешеве|проиндексир|вырастут|вырастет|снизятся|"
    r"выплат|пособи|пенси|индексац|компенсац|льгот|субсиди|"
    r"запретил(и)?|разрешил(и)?|отменил(и)?|штраф|пошлин|акциз|"
    r"погиб|пострада|пожар|взрыв|авари|обруш|эвакуац|затопил|"
    r"наводнен|землетрясен|столкновен|"
    r"отмен(а|ены|или) рейс|задерж(ка|ки) рейс|"
    r"ввели ограничен|сняли ограничен|закрыл(и)? аэропорт)",
    re.IGNORECASE)

# Практическое предупреждение: действовать нужно читателю, а не автору.
PRACTICAL = re.compile(
    r"(предупреди(л|ла|ли)|напомина(ет|ют)).{0,60}"
    r"(мошенн|обман|фишинг|поддельн|двойник|опасн|риск|"
    r"измен(ени|ится)|расписан|перебо|отключен|ограничен|"
    r"похолодан|шторм|ураган|метел|гололёд)", re.IGNORECASE)

INTENTION = re.compile(
    r"\b(пообеща(л|ла|ли)|намер(ен|ена|ены)|планиру(ет|ют)|"
    r"потребова(л|ла|ли)|призва(л|ла|ли)|предложи(л|ла|ли)|"
    r"выступи(л|ла|ли) (за|против|с)|анонсирова(л|ла|ли)|"
    r"пригрози(л|ла|ли)|хочет|хотят|собира(ется|ются)|"
    r"рассматрива(ет|ют)ся|может (быть )?(введ|принят))\b",
    re.IGNORECASE)

PROCEDURE = re.compile(
    r"(законопроект|поручи(л|ла|ли)|обсуди(л|ла|ли)|"
    r"(провел|начал|завершил)(и)? (встречу|переговор|совещан)|"
    r"встрети(лся|лась|лись)|встреч(а|у|и) с |принял участие|"
    r"заяви(л|ла|ли)|сообщи(л|ла|ли)|прокомментирова|"
    r"оцени(л|ла|ли)|назва(л|ла|ли)|поздрави(л|ла|ли)|"
    r"поблагодари(л|ла|ли)|отмети(л|ла|ли)|подчеркну(л|ла|ли)|"
    r"напомни(л|ла|ли)|рассказа(л|ла|ли)|объясни(л|ла|ли)|"
    r"удивлен|характеризова|показало кадры)", re.IGNORECASE)

QUOTE_LEAD = re.compile(r"^[А-ЯЁ][а-яё]+( [А-ЯЁ][а-яё]+)?:\s")

JUNK = re.compile(
    r"(гороскоп|астролог|знак(и|ов)? зодиака|нумеролог|"
    r"партнёрский материал|на правах рекламы|фоторепортаж|"
    r"видео дня|фото дня|подборка|топ-?\d+|что посмотреть|"
    r"как выбрать|лайфхак|тест:|викторина|"
    r"информация о ценных бумагах|перечень|реестр)", re.IGNORECASE)

OFF_TOPIC = re.compile(
    r"(чемпионат|турнир|матч |сборная|олимпиад|гран-при|"
    r"футбол|хоккей|баскетбол|шахматн|"
    r"кинофестивал|премьер(а|у) фильма|концерт|выставк(а|у)|"
    r"похорон|церемони(я|ю) прощания|мемориал|реставрац|"
    r"экспедиц|погребение|раскопк)", re.IGNORECASE)


def prefilter(title: str) -> tuple[bool, str]:
    t = (title or "").strip()
    if len(t) < 15:
        return False, "слишком короткий заголовок"
    if JUNK.search(t):
        return False, "служебный или рекламный материал"
    if OFF_TOPIC.search(t):
        return False, "вне тематики канала"
    if PRACTICAL.search(t):
        return True, ""
    if HAPPENED.search(t):
        return True, ""
    if QUOTE_LEAD.match(t):
        return False, "заголовок-цитата"
    if INTENTION.search(t):
        return False, "стадия намерения"
    if PROCEDURE.search(t):
        return False, "внутренняя процедура"
    return True, ""
