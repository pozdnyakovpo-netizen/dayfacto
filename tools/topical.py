"""Тематический фильтр для широких правовых лент.

Гарант, КонсультантПлюс и Право.ру публикуют всё право подряд: налоги,
медицину, ЖКХ, трудовые споры. Среди этого проскакивает то, чего нет
нигде больше — судебная практика по классификации товаров и
подтверждению таможенной стоимости.

Фильтр пропускает только материалы с таможенной лексикой. Работает по
ключевым словам, до обращения к модели, поэтому ничего не стоит.

Используется в tools/build_outbox.py для источников из BROAD_SOURCES.
"""

import re

BROAD_SOURCES = ("Гарант", "КонсультантПлюс", "Право.ру",
                 "Российская газета", "Правительство России",
                 "LogiRus", "SeaNews")

# Достаточно одного совпадения, чтобы материал прошёл дальше.
CUSTOMS_TERMS = [
    # ядро
    "таможен", "тн вэд", "тнвэд", "вэд ", "декларант", "декларировани",
    "таможенная стоимость", "таможенной стоимости", "классификац",
    "ввозн", "вывозн", "импорт", "экспорт", "пошлин", "акциз",
    # процедуры и документы
    "деклараци", "выпуск товаров", "транзит", "свх", "склад временного",
    "предварительное решение", "происхождени товар", "преференц",
    "сертификат соответствия", "декларация соответствия", "еаэс",
    "евразийск", "таможенный союз", "фтс", "росаккредитаци",
    # споры
    "корректировк таможенной", "ктс", "отказ в выпуске",
    "административн правонарушени", "16.2", "16.7",
    # смежное
    "валютн контрол", "репатриац", "внешнеторгов", "внешнеэкономическ",
    "россельхознадзор", "фитосанитарн", "ветеринарн сертификат",
    "маркировк товаров", "честный знак", "параллельн импорт",
]

# Если материал явно из другой области — режем даже при совпадении выше.
OFF_TOPIC = [
    "алимент", "пенси", "жкх", "капитальн ремонт", "医",
    "медицинск помощ", "диспансер", "школ", "абитуриент", "вуз",
    "трудов договор", "отпуск", "больничн", "детск пособи",
    "ипотек", "материнск капитал", "жилищн", "наследств",
    "уголовн дел о взятк", "госизмен",
]


def _norm(s: str) -> str:
    s = (s or "").lower().replace("ё", "е")
    return re.sub(r"\s+", " ", s)


def is_broad_source(name: str) -> bool:
    return any(name.startswith(b) for b in BROAD_SOURCES)


def customs_relevant(title: str, body: str = "") -> bool:
    """Есть ли в материале таможенная тематика."""
    text = _norm(title + " " + (body or "")[:1200])
    if not any(t.replace("ё", "е") in text for t in CUSTOMS_TERMS):
        return False
    # если тема явно чужая и таможенных слов мало — отсекаем
    hits = sum(1 for t in CUSTOMS_TERMS if t.replace("ё", "е") in text)
    if hits < 2 and any(o in text for o in OFF_TOPIC):
        return False
    return True


def topical_skip(source_name: str, title: str, body: str = "") -> str:
    """Причина отсева или пустая строка."""
    if not is_broad_source(source_name):
        return ""
    if customs_relevant(title, body):
        return ""
    return "не таможенная тема"
